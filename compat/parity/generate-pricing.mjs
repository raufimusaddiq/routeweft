// Generates internal/pricing/data_gen.go from the oracle's default price catalog
// (open-sse/providers/pricing.js: MODEL_PRICING, PROVIDER_PRICING, PATTERN_PRICING)
// and records what the oracle's own getPricingForModel and calculateCostFromTokens
// answer for a probe set (internal/pricing/testdata/pricing_pin.json), so the Go
// tests replay the oracle instead of a copy of it (#273). Run:
//
//   eval "$(node compat/parity/resolve-oracle.mjs | sed 's/^/export /')"
//   node compat/parity/generate-pricing.mjs           # rewrite both files
//   node compat/parity/generate-pricing.mjs --check   # fail if the oracle now differs
//
// No provider is called.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { load, pin } from './oracle.mjs';

const oracle = await load('open-sse/providers/pricing.js', {});
const q = JSON.stringify;
const rates = value => `Rates{Input: ${value.input ?? 0}, Output: ${value.output ?? 0}, Cached: ${value.cached ?? 0}, Reasoning: ${value.reasoning ?? 0}, CacheCreation: ${value.cache_creation ?? 0}}`;
const entries = object => Object.entries(object).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const output = `// Code generated by compat/parity/generate-pricing.mjs; DO NOT EDIT.
// Source: open-sse/providers/pricing.js at ${pin}.
package pricing

var modelPricing = map[string]Rates{
${entries(oracle.MODEL_PRICING).map(([model, value]) => `${q(model)}: ${rates(value)},`).join('\n')}
}

var providerPricing = map[string]map[string]Rates{
${entries(oracle.PROVIDER_PRICING).map(([provider, models]) => `${q(provider)}: {\n${entries(models).map(([model, value]) => `${q(model)}: ${rates(value)},`).join('\n')}\n},`).join('\n')}
}

var patternPricing = []patternRates{
${oracle.PATTERN_PRICING.map(({ pattern, pricing }) => `{Pattern: ${q(pattern)}, Rates: ${rates(pricing)}},`).join('\n')}
}
`;
const formatted = execFileSync('gofmt', { input: output, encoding: 'utf8' });

// Probes: every catalog key, every key with a vendor prefix and in another case, a
// provider-specific hit, pattern hits and misses.
const models = new Set([...Object.keys(oracle.MODEL_PRICING)]);
const probes = [];
for (const model of models) {
  probes.push({ provider: '', model }, { provider: 'openai', model }, { provider: 'x', model: `vendor/${model}` }, { provider: 'x', model: model.toUpperCase() });
}
for (const [provider, table] of Object.entries(oracle.PROVIDER_PRICING)) for (const model of Object.keys(table)) probes.push({ provider, model }, { provider: 'other', model });
for (const { pattern } of oracle.PATTERN_PRICING) {
  const sample = pattern.replaceAll('*', 'zz');
  probes.push({ provider: 'p', model: sample }, { provider: 'p', model: `v/${sample}` }, { provider: 'p', model: sample.toUpperCase() });
}
probes.push({ provider: 'p', model: '' }, { provider: '', model: 'definitely-not-a-priced-model' }, { provider: 'gh', model: 'gpt-5.3-codex' }, { provider: 'github', model: 'gpt-5.3-codex' });
const lookup = probes.map(({ provider, model }) => ({ provider, model, pricing: oracle.getPricingForModel(provider, model) }));

const tokenCases = [
  { name: 'plain input and output', tokens: { prompt_tokens: 1000, completion_tokens: 500 } },
  { name: 'input_tokens and output_tokens spellings', tokens: { input_tokens: 1000, output_tokens: 500 } },
  { name: 'cache read is a subset of the prompt', tokens: { prompt_tokens: 1000, completion_tokens: 100, cached_tokens: 400 } },
  { name: 'cache_read_input_tokens spelling', tokens: { prompt_tokens: 1000, completion_tokens: 100, cache_read_input_tokens: 400 } },
  { name: 'cache creation is a subset too', tokens: { prompt_tokens: 1000, completion_tokens: 100, cached_tokens: 300, cache_creation_input_tokens: 200 } },
  { name: 'cache larger than the prompt never charges negative input', tokens: { prompt_tokens: 100, completion_tokens: 10, cached_tokens: 400 } },
  { name: 'reasoning tokens are charged on top of the output', tokens: { prompt_tokens: 100, completion_tokens: 50, reasoning_tokens: 30 } },
  { name: 'empty', tokens: {} },
];
const ratesCases = [
  { name: 'all five rates', pricing: { input: 3, output: 15, cached: 0.3, reasoning: 22.5, cache_creation: 3.75 } },
  { name: 'only input and output: cached, reasoning and creation fall back', pricing: { input: 3, output: 15 } },
  { name: 'free output', pricing: { input: 0.042, output: 0 } },
  { name: 'zero cached falls back to input', pricing: { input: 2, output: 8, cached: 0 } },
];
const cost = [];
for (const rate of ratesCases) for (const token of tokenCases) cost.push({ pricing: rate.pricing, tokens: token.tokens, name: `${rate.name} / ${token.name}`, cost: oracle.calculateCostFromTokens(token.tokens, rate.pricing) });

const pinned = JSON.stringify({ oracle: "raufimusaddiq/literouter", sha: pin, lookup, cost }) + '\n';
const dataFile = new URL('../../internal/pricing/data_gen.go', import.meta.url);
const pinFile = new URL('../../internal/pricing/testdata/pricing_pin.json', import.meta.url);
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(dataFile, 'utf8').replace(/at [0-9a-f]{40}/, 'at SHA'), formatted.replace(/at [0-9a-f]{40}/, 'at SHA'), 'price catalog disagrees with the oracle; regenerate');
  const committed = JSON.parse(readFileSync(pinFile, 'utf8'));
  assert.deepEqual({ ...JSON.parse(pinned), sha: null }, { ...committed, sha: null }, 'oracle pricing answers differ from the pin; regenerate');
  console.log(`${pin}: price catalog and pin match the oracle`);
} else {
  writeFileSync(dataFile, formatted);
  writeFileSync(pinFile, pinned);
  console.log(`${pin}: ${Object.keys(oracle.MODEL_PRICING).length} models, ${lookup.length} lookups, ${cost.length} cost cases`);
}
