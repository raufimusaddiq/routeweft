// Regenerates internal/providers/registry/seeds_gen.go from the pinned
// LiteRouter registry. Model seeds are the oracle's, not a hand-kept list:
// running this with a new pin is the only way the file changes.
//
//   ORACLE_DIR=/opt/9router node compat/parity/generate-seeds.mjs
import { writeFileSync } from 'node:fs';
import { activeProviderIds, providerFacts } from './providers.mjs';

const entries = activeProviderIds()
  .map(entry => ({ id: entry.id, ...providerFacts(entry.id) }))
  .sort((a, b) => a.id.localeCompare(b.id));

const quote = value => JSON.stringify(value);

const rows = entries
  .filter(entry => entry.models.length > 0)
  .map(entry => {
    const models = entry.models
      .map(model => `\t\t{ID: ${quote(model.id)}, Name: ${quote(model.name)}, ContextWindow: ${model.contextWindow}},`)
      .join('\n');
    return `\t${quote(entry.id)}: {\n${models}\n\t},`;
  })
  .join('\n');

const file = `// Code generated by compat/parity/generate-seeds.mjs from the pinned LiteRouter
// registry. DO NOT EDIT.
//
// Source: open-sse/providers/registry/*.js at the pin recorded in
// compat/parity/oracle.mjs. Every active provider that ships models gets its
// seeds here, so a fresh install can route a model for every provider LiteRouter
// serves without the operator running discovery by hand.

package registry

// seedModels is the oracle's per-provider model seed list.
var seedModels = map[string][]SeedModel{
${rows}
}
`;

writeFileSync('internal/providers/registry/seeds_gen.go', file);
console.log(`wrote ${entries.filter(e => e.models.length).length} providers, ${entries.reduce((n, e) => n + e.models.length, 0)} models`);
