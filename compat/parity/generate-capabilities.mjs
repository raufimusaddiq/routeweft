import { writeFileSync, readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { capabilityOracle } from './capabilities.mjs';

const { oracle, data, regex, pin } = await capabilityOracle();
const q = JSON.stringify;
const field = key => key === 'pdf' ? 'PDF' : key[0].toUpperCase() + key.slice(1);
const caps = value => '{' + Object.entries({ ...oracle.DEFAULT_CAPABILITIES, ...value }).map(([key, value]) => {
  if (key === 'thinkingRange') return value ? `ThinkingRange: BudgetRange{Min: ${value.min}, Max: ${value.max}, Set: true}` : 'ThinkingRange: BudgetRange{}';
  return `${field(key)}: ${q(value ?? '')}`;
}).join(', ') + '}';
const entries = object => Object.entries(object).sort(([a], [b]) => a.localeCompare(b));
const table = object => '{\n' + entries(object).map(([key, value]) => `${q(key)}: ${caps(value)},`).join('\n') + '\n}';
const output = `// Code generated by compat/parity/generate-capabilities.mjs; DO NOT EDIT.
// Source: open-sse/providers/capabilities.js at ${pin}.
package capabilities
var defaults = Capabilities${caps({})}
var modelData = map[string]Capabilities${table(oracle.MODEL_CAPABILITIES)}
var providerData = map[string]map[string]Capabilities{
${entries(oracle.PROVIDER_CAPABILITIES).map(([key, value]) => `${q(key)}: ${table(value)},`).join('\n')}
}
var patternData = []patternEntry{
${oracle.PATTERN_CAPABILITIES.map(({ pattern, caps: value }) => `{Pattern: ${q(pattern)}, Caps: Capabilities${caps(value)}},`).join('\n')}
}
var aliases = map[string]string{${entries(data.aliases).map(([k,v]) => `${q(k)}:${q(v)},`).join('\n')}}
var commandTextOnly = []string{${data.textOnly.map(q).join(',')}}
var commandDefault = Capabilities${caps(oracle.getCapabilitiesForModel('commandcode', '__unknown_capability_model__'))}
var notVisionPattern = ${q(regex[0])}
var visionPattern = ${q(regex[1])}
`;
const formatted = execFileSync('gofmt', { input: output, encoding: 'utf8' });
const target = 'internal/providers/capabilities/data_gen.go';
if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), formatted, 'capability data disagrees with the pin; regenerate');
else writeFileSync(target, formatted);
