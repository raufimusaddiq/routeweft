// The divergence ledger and its sign-off sheet (#274).
//
// Every way Routeweft is known to differ from the oracle is accounted for in one of
// two places: a D row in docs/PARITY.md 6.1 (a decision: approved, or required), or a
// group of the pinned protocol-leg differential (compat/parity/divergences.json), each
// tied to a D row, a register item of PARITY 6.3-6.12 or a section. This reads both and
// writes docs/DIVERGENCE_LEDGER.md: the counts, every D row with its state, the groups
// by leg, and a block to sign. Nothing here reads the oracle.
//
//   node compat/parity/ledger.mjs            # rewrite docs/DIVERGENCE_LEDGER.md
//   node compat/parity/ledger.mjs --check    # fail if it is stale or a reference dangles
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const parity = '\n' + readFileSync(new URL('docs/PARITY.md', root), 'utf8');
const ledger = JSON.parse(readFileSync(new URL('compat/parity/divergences.json', root), 'utf8'));
const legsPin = JSON.parse(readFileSync(new URL('internal/parity/testdata/legs_pin.json', root), 'utf8'));

// ---- D rows: "| D<n> | text | refs | position |" ------------------------------
const rows = [...parity.matchAll(/\n\| (D\d+) \| (.*?) \| ([^|\n]*) \| ([^\n]*) \|/g)].map(([, id, text, refs, position]) => {
  const pending = /Decision required/i.test(text);
  const approved = /\*\*Approved\*\*|^Approved\b/i.test(text) || !pending;
  return { id, text: text.replace(/\s+/g, ' '), refs: refs.trim(), position: position.trim(), state: pending && !/\*\*Approved\*\*/.test(text) ? 'decision required' : 'approved', approved };
});
assert.ok(rows.length >= 30, 'no D rows were read from docs/PARITY.md');
const byId = new Map();
for (const row of rows) {
  assert.ok(!byId.has(row.id), `${row.id} is defined twice`);
  byId.set(row.id, row);
}

// ---- references resolve ------------------------------------------------------
const resolves = ref => {
  if (ref.startsWith('§')) return parity.includes(`\n### ${ref.slice(1)} `) || parity.includes(`\n## ${ref.slice(1)} `);
  if (/^D\d+$/.test(ref)) return byId.has(ref);
  return parity.includes(`\n| ${ref} |`) || parity.includes(`- **${ref}**`);
};
const dangling = ledger.entries.filter(entry => !resolves(entry.ref));

// ---- the sheet ---------------------------------------------------------------
const legs = new Map();
for (const entry of ledger.entries) {
  const key = `${entry.direction} ${entry.leg}`;
  if (!legs.has(key)) legs.set(key, []);
  legs.get(key).push(entry);
}
const usedBy = new Map();
for (const entry of ledger.entries) usedBy.set(entry.ref, (usedBy.get(entry.ref) ?? 0) + 1);
const pending = rows.filter(row => row.state === 'decision required');
const kindName = { changed: 'differs', 'only-oracle': 'oracle only', 'only-routeweft': 'Routeweft only', 'go-error': 'Routeweft refuses', 'oracle-error': 'oracle fails' };
const cell = text => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const short = text => (text.length > 150 ? `${text.slice(0, 147)}...` : text);

const lines = [];
lines.push('# Divergence ledger and sign-off sheet', '',
  '<!-- Generated by `node compat/parity/ledger.mjs` from docs/PARITY.md and compat/parity/divergences.json. Do not edit by hand; `--check` fails when it is stale. -->', '',
  `Oracle for the protocol-leg differential: LiteRouter \`main\` \`${legsPin.sha}\` (the commit \`compat/parity/generate-protocol-legs.mjs\` last recorded). The report is a statement of what is known, not of what is correct: a difference listed here has an owner decision behind it or is waiting for one.`, '',
  '## Summary', '',
  `| | |`, `|---|---|`,
  `| D rows (PARITY 6.1) | ${rows.length} |`,
  `| approved | ${rows.length - pending.length} |`,
  `| **decision required** | **${pending.length}** |`,
  `| protocol-leg differences recorded | ${ledger.entries.length} (${ledger.entries.filter(e => e.direction === 'request').length} request, ${ledger.entries.filter(e => e.direction === 'response').length} response) over ${legs.size} legs |`,
  `| accounted for by a D row | ${ledger.entries.filter(e => e.ref.startsWith('D')).length} |`,
  `| accounted for by an earlier register item or section (PARITY 6.3-6.12) | ${ledger.entries.filter(e => !e.ref.startsWith('D')).length} |`,
  `| references that do not resolve | ${dangling.length} |`, '',
  'The earlier register items (V1-V40, G1-G13, C1-C2, A1-A8, F1-F3, R1-R8, M-items and the sections) were written by hand while the legs were built (#119) and have no state of their own; they are listed here so the owner can sign them with the D rows.', '',
  '## Decisions required', '',
  'Each is a difference the owner has not yet approved. Approving one means replacing "Decision required" with an approval in its D row; refusing one means a change to the code.', '',
  '| D row | what differs | differential groups |', '|---|---|---|');
for (const row of pending) lines.push(`| ${row.id} | ${cell(short(row.text.replace(/^Decision required:\s*/i, '')))} | ${usedBy.get(row.id) ?? 0} |`);
lines.push('', '## Approved', '', '| D row | decision |', '|---|---|');
for (const row of rows.filter(r => r.state === 'approved')) lines.push(`| ${row.id} | ${cell(short(row.text))} |`);
lines.push('', '## Protocol-leg differences by leg', '',
  'Each line is one group: a path where the legs differ, the item that accounts for it, and the first case that shows it (oracle value, then Routeweft value).', '');
for (const [key, entries] of [...legs.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`### ${key}`, '', '| difference | path | account | example |', '|---|---|---|---|');
  for (const entry of entries) lines.push(`| ${kindName[entry.kind] ?? entry.kind} | \`${cell(entry.path)}\` | ${entry.ref} | ${cell(entry.example.case)}: ${cell(short(entry.example.oracle))} / ${cell(short(entry.example.routeweft))} |`);
  lines.push('');
}
lines.push('## Not covered by the differential', '',
  '- the response legs whose upstream is a binary wire: Kiro (EventStream), Cursor, Command Code;',
  '- non-streaming response bodies (the oracle converts streams only; Routeweft\'s buffered conversions are tested against its own expectations);',
  '- control workflows other than combos, API keys and model aliases (provider nodes, connections, settings, pricing, usage), beyond the route inventory (`compat/parity/inventory.mjs`) and the pool and pricing pins;',
  '- anything that needs a live provider.', '',
  '## Sign-off', '',
  'I have read the decisions above. Those marked approved stand; for those marked "decision required" I direct the change recorded against each in PARITY 6.1.', '',
  '| | |', '|---|---|', '| Owner | |', '| Date | |', '| Oracle commit | |', '| Routeweft commit | |', '| Decisions approved | |', '| Decisions refused (change requested) | |', '');
const sheet = lines.join('\n');

const file = new URL('docs/DIVERGENCE_LEDGER.md', root);
if (process.argv.includes('--check')) {
  assert.deepEqual(dangling, [], `ledger references that do not resolve in docs/PARITY.md: ${dangling.map(e => `${e.leg} ${e.path} -> ${e.ref}`).join('; ')}`);
  assert.equal(readFileSync(file, 'utf8'), sheet, 'docs/DIVERGENCE_LEDGER.md is stale; run node compat/parity/ledger.mjs');
  console.log(`divergence ledger is current: ${rows.length} D rows (${pending.length} awaiting a decision), ${ledger.entries.length} differential groups`);
} else {
  assert.deepEqual(dangling, [], `ledger references that do not resolve: ${dangling.map(e => `${e.leg} ${e.path} -> ${e.ref}`).join('; ')}`);
  writeFileSync(file, sheet);
  console.log(`wrote docs/DIVERGENCE_LEDGER.md: ${rows.length} D rows (${pending.length} awaiting a decision), ${ledger.entries.length} differential groups`);
}
